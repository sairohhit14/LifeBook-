/**
 * db.json backup/restore — scheduled snapshots to Supabase Storage.
 *
 * Storage: PRIVATE bucket `db-backups`, objects `db-<ISO-timestamp>.json.gz`.
 * A private bucket is the recovery point for the user database, so it must
 * never be a public one (Supabase denies reads without the service key).
 * Restore: `npm run backup:restore -- --latest` (or `--file <name>` /
 * no flags to list). Snapshots are pruned to BACKUP_MAX_SNAPSHOTS.
 *
 * Setup (one-time, in the Supabase dashboard or SQL editor):
 *   insert into storage.buckets (id, name, public)
 *   values ('db-backups', 'db-backups', false)
 *   on conflict (id) do nothing;
 *
 * ponytail: whole-file gzip snapshots on a fixed interval — no WAL, no
 * incremental diffs. Right-sized for the JSON-file db; the upgrade path is
 * Postgres PITR (Supabase managed backups) if db.json ever outgrows this.
 */
import fs from "fs";
import path from "path";
import zlib from "zlib";
import { promisify } from "util";

const gzip = promisify(zlib.gzip);
const gunzip = promisify(zlib.gunzip);

export const BACKUP_BUCKET = "db-backups";
export const BACKUP_INTERVAL_MS = 6 * 60 * 60 * 1000; // every 6 hours
export const BACKUP_MAX_SNAPSHOTS = 30; // ~7.5 days of history

const SUPABASE_URL_ENV = (process.env.SUPABASE_URL || "").replace(/\/rest\/v1\/?$/, "");
const SUPABASE_KEY_ENV = process.env.SUPABASE_KEY || "";

// Guards against .env.example placeholders ("your-project-ref…" /
// "your-service-role-key") counting as a live backend — that made every
// request fire doomed fetches. Requires https; self-hosted/custom hosts pass.
export function isRealSupabaseConfig(url: string, key: string): boolean {
  if (!url || !key) return false;
  if (!/^https:\/\/.+/.test(url)) return false;
  return !/your-project-ref|your-service-role-key/.test(`${url} ${key}`);
}

export function backupsConfigured(): boolean {
  return isRealSupabaseConfig(SUPABASE_URL_ENV, SUPABASE_KEY_ENV);
}

function backupHeaders(extra: Record<string, string> = {}): Record<string, string> {
  return {
    apikey: SUPABASE_KEY_ENV,
    Authorization: `Bearer ${SUPABASE_KEY_ENV}`,
    ...extra,
  };
}

function backupObjectName(now: Date = new Date()): string {
  return `db-${now.toISOString().replace(/[:.]/g, "-")}.json.gz`;
}

/** Upload the current db file as a gzipped snapshot. Returns the object name. */
export async function uploadBackup(dbPath: string, now: Date = new Date()): Promise<string> {
  if (!backupsConfigured()) {
    throw new Error("Backups are not configured: set SUPABASE_URL and SUPABASE_KEY.");
  }
  const objectName = backupObjectName(now);
  const payload = await gzip(fs.readFileSync(dbPath));

  const res = await fetch(`${SUPABASE_URL_ENV}/storage/v1/object/${BACKUP_BUCKET}/${objectName}`, {
    method: "POST",
    headers: backupHeaders({
      "Content-Type": "application/gzip",
      "x-upsert": "true",
    }),
    body: new Uint8Array(payload),
  });
  if (!res.ok) {
    throw new Error(`Backup upload failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
  }
  return objectName;
}

/** List snapshot names, oldest first. */
export async function listBackups(): Promise<string[]> {
  if (!backupsConfigured()) {
    throw new Error("Backups are not configured: set SUPABASE_URL and SUPABASE_KEY.");
  }
  const res = await fetch(
    `${SUPABASE_URL_ENV}/storage/v1/object/list/${BACKUP_BUCKET}?limit=1000&sort_by=created_at&sort_order=desc`,
    { headers: backupHeaders() },
  );
  if (!res.ok) {
    throw new Error(`Backup list failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
  }
  const rows = (await res.json()) as Array<{ name?: string }>;
  return rows
    .map((r) => r.name || "")
    .filter((n) => /^db-.*\.json\.gz$/.test(n))
    .sort();
}

/** Download a snapshot and return the decompressed db JSON string. */
export async function downloadBackup(objectName: string): Promise<string> {
  if (!backupsConfigured()) {
    throw new Error("Backups are not configured: set SUPABASE_URL and SUPABASE_KEY.");
  }
  // Object names are generated by backupObjectName(); the test below pins that
  // format — this guard rejects anything path-shaped before it hits the URL.
  if (!/^db-[A-Za-z0-9-]+\.json\.gz$/.test(objectName)) {
    throw new Error(`Invalid backup object name: ${objectName}`);
  }
  const res = await fetch(`${SUPABASE_URL_ENV}/storage/v1/object/${BACKUP_BUCKET}/${objectName}`, {
    headers: backupHeaders(),
  });
  if (!res.ok) {
    throw new Error(`Backup download failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  return (await gunzip(buf)).toString("utf-8");
}

/** Delete snapshots beyond BACKUP_MAX_SNAPSHOTS (newest kept). */
export async function pruneBackups(): Promise<string[]> {
  const names = await listBackups();
  const excess = names.slice(0, Math.max(0, names.length - BACKUP_MAX_SNAPSHOTS));
  for (const name of excess) {
    const res = await fetch(`${SUPABASE_URL_ENV}/storage/v1/object/${BACKUP_BUCKET}/${name}`, {
      method: "DELETE",
      headers: backupHeaders(),
    });
    if (!res.ok) {
      console.error(`[Backup] Prune failed for ${name} (${res.status})`);
    }
  }
  return excess;
}

/**
 * Snapshot + prune. Never throws into request paths: logs failures and
 * keeps going — a failed backup must not take the app down.
 */
export async function runBackupCycle(dbPath: string): Promise<string | null> {
  if (!backupsConfigured()) return null;
  try {
    if (!fs.existsSync(dbPath)) return null;
    const name = await uploadBackup(dbPath);
    console.log(`[Backup] Snapshot uploaded: ${name}`);
    const pruned = await pruneBackups();
    if (pruned.length) console.log(`[Backup] Pruned ${pruned.length} old snapshot(s)`);
    return name;
  } catch (err: any) {
    console.error("[Backup] Snapshot failed:", err.message);
    return null;
  }
}

let lastBackupTime = 0;
// ponytail: per-instance debounce — N warm serverless instances may each fire
// near the interval boundary, yielding a few duplicate snapshots; pruning to
// BACKUP_MAX_SNAPSHOTS caps the drift.
const BACKUP_MIN_GAP_MS = BACKUP_INTERVAL_MS;

/** Vercel hook: run at most once per interval across warm instances. */
export function maybeRunScheduledBackup(dbPath: string): void {
  const now = Date.now();
  if (now - lastBackupTime < BACKUP_MIN_GAP_MS) return;
  lastBackupTime = now;
  runBackupCycle(dbPath).catch(() => { /* logged in runBackupCycle */ });
}

/** Restore CLI: overwrite the local db file with a snapshot. */
export async function restoreBackup(objectName: string, dbPath: string): Promise<void> {
  const json = await downloadBackup(objectName);
  JSON.parse(json); // refuse to clobber the live db with a corrupt snapshot
  const tmp = dbPath + ".restore-tmp";
  fs.writeFileSync(tmp, json);
  fs.renameSync(tmp, dbPath);
  console.log(`[Backup] Restored ${objectName} -> ${dbPath}`);
}

// ---------------- restore CLI ----------------
// Usage:
//   npx tsx server/db-backup.ts                 # list snapshots
//   npx tsx server/db-backup.ts --latest        # restore newest
//   npx tsx server/db-backup.ts --file db-...   # restore specific
//   DB_PATH=/path/to/db.json npx tsx server/db-backup.ts --latest
async function runCli(): Promise<void> {
  const args = process.argv.slice(2);
  const dbPath = process.env.DB_PATH || path.join(process.cwd(), "db.json");

  if (args.length === 0) {
    const names = await listBackups();
    console.log(names.length ? names.join("\n") : "(no snapshots found)");
    return;
  }
  if (args[0] === "--latest") {
    const names = await listBackups();
    if (names.length === 0) throw new Error("No snapshots found to restore.");
    await restoreBackup(names[names.length - 1], dbPath);
    return;
  }
  if (args[0] === "--file" && args[1]) {
    await restoreBackup(args[1], dbPath);
    return;
  }
  throw new Error("Usage: tsx server/db-backup.ts [--latest | --file <name>]");
}

if (process.argv[1] && process.argv[1].endsWith("db-backup.ts")) {
  runCli().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
